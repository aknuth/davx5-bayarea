#!/usr/bin/env python3
#
# Bay Area Sync: generates app-ose string resources that override all strings of :core (and its
# translations) which contain the name "DAVx⁵". Most strings use @string/app_name, so only few are affected.
#
# Re-run after updating the l10n submodule:  python3 scripts/bayarea-branding-strings.py
#

import re
from pathlib import Path

APP_NAME = "Bay Area Sync"
ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "core/src/main/res/values/strings.xml"
SOURCES = [ROOT / "core/src/main/res", ROOT / "l10n/translations/ose"]
TARGET = ROOT / "app-ose/src/main/res"
FILE_NAME = "bayarea_branding_strings.xml"

STRING_RE = re.compile(r'<string name="([^"]+)"([^>]*)>(.*?)</string>', re.S)


def read_strings(strings_xml: Path) -> dict[str, tuple[str, str]]:
    return {name: (attrs, text) for name, attrs, text in STRING_RE.findall(strings_xml.read_text(encoding="utf-8"))}


def rebrand(name: str, text: str) -> str | None:
    if name == "app_name":
        return APP_NAME
    if "DAVx⁵" in text:
        return text.replace("DAVx⁵", APP_NAME)
    return None


base_strings = read_strings(BASE)

# overrides per values directory: {"values-de": {name: (attrs, text)}}
overrides: dict[str, dict[str, tuple[str, str]]] = {}
for source in SOURCES:
    for strings_xml in sorted(source.glob("values*/strings.xml")):
        for name, (attrs, text) in read_strings(strings_xml).items():
            if (new_text := rebrand(name, text)) is not None:
                overrides.setdefault(strings_xml.parent.name, {})[name] = (attrs, new_text)

# Every overridden string needs a default (otherwise lint reports ExtraTranslation), even if the
# default text doesn't contain the name.
for values_dir in list(overrides):
    for name in overrides[values_dir]:
        if name not in overrides.get("values", {}) and name in base_strings:
            overrides.setdefault("values", {})[name] = base_strings[name]

for old_file in TARGET.glob(f"values*/{FILE_NAME}"):
    old_file.unlink()
for values_dir, strings in overrides.items():
    target_file = TARGET / values_dir / FILE_NAME
    target_file.parent.mkdir(parents=True, exist_ok=True)
    target_file.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/bayarea-branding-strings.py, do not edit. -->\n'
        '<resources xmlns:tools="http://schemas.android.com/tools">\n'
        + "\n".join(f'    <string name="{name}"{attrs}>{text}</string>' for name, (attrs, text) in sorted(strings.items()))
        + "\n</resources>\n",
        encoding="utf-8"
    )
