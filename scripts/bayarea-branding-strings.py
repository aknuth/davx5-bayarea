#!/usr/bin/env python3
#
# Bay Area Sync: generates app-ose string resources that override all strings of :core (and its
# translations) which contain the name "DAVx⁵". Most strings use @string/app_name, so only few are affected.
#
# Re-run after updating the l10n submodule:  python3 scripts/bayarea-branding-strings.py
#

import re
from pathlib import Path

APP_NAME = "Bay Area Sync"
ROOT = Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "core/src/main/res", ROOT / "l10n/translations/ose"]
TARGET = ROOT / "app-ose/src/main/res"
FILE_NAME = "bayarea_branding_strings.xml"

STRING_RE = re.compile(r'<string name="([^"]+)"([^>]*)>(.*?)</string>', re.S)

for source in SOURCES:
    for strings_xml in sorted(source.glob("values*/strings.xml")):
        overrides = []
        for name, attrs, text in STRING_RE.findall(strings_xml.read_text(encoding="utf-8")):
            if name == "app_name":
                text = APP_NAME
            elif "DAVx⁵" in text:
                text = text.replace("DAVx⁵", APP_NAME)
            else:
                continue
            overrides.append(f'    <string name="{name}"{attrs}>{text}</string>')

        target_file = TARGET / strings_xml.parent.name / FILE_NAME
        if overrides:
            target_file.parent.mkdir(parents=True, exist_ok=True)
            target_file.write_text(
                '<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by scripts/bayarea-branding-strings.py, do not edit. -->\n'
                '<resources xmlns:tools="http://schemas.android.com/tools">\n'
                + "\n".join(overrides) + "\n</resources>\n",
                encoding="utf-8"
            )
        elif target_file.exists():
            target_file.unlink()
